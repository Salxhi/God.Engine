nivel = int(input("Seleccione un nivel (1 a 4): "))

if nivel == 1:
    print("Dificultad: Fácil.")
elif nivel == 2:
    print("Dificultad: Medio.")
elif nivel == 3:
    print("Dificultad: Difícil.")
elif nivel == 4:
    print("Dificultad: Extremo.")
else:
    print("Seleccione un nivel entre 1 y 4.")
